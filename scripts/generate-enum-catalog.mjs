import { execFileSync } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const uiRoot = resolve(scriptDir, '..');
const repositoryRoot = resolve(uiRoot, '..');
const schemaPath = resolve(
  repositoryRoot,
  'schema/api/enum-catalog-v1.schema.json',
);
const outputPath = resolve(
  uiRoot,
  'packages/types/src/generated/enum-catalog.ts',
);
const checkOnly = process.argv.includes('--check');
const temporaryRoot = checkOnly
  ? await mkdtemp(resolve(uiRoot, '.enum-catalog-check-'))
  : undefined;
const generatedSchemaPath = temporaryRoot
  ? resolve(temporaryRoot, 'enum-catalog-v1.schema.json')
  : schemaPath;
const generatedOutputPath = temporaryRoot
  ? resolve(temporaryRoot, 'enum-catalog.ts')
  : outputPath;

function assertSchema(schema) {
  if (schema.schema_version !== 1 || !Array.isArray(schema.enums)) {
    throw new Error('Unsupported enum catalog schema');
  }
  for (const definition of schema.enums) {
    if (
      typeof definition.name !== 'string' ||
      !Array.isArray(definition.members) ||
      definition.members.length === 0
    ) {
      throw new Error('Malformed enum catalog definition');
    }
  }
}

function renderCatalog(schema) {
  const catalog = {};
  const metadata = {};
  const memberKeyTemplate = ['$', '{Name}.', '$', '{EnumValue<Name>}'].join('');
  for (const definition of schema.enums) {
    catalog[definition.name] = definition.members.map(
      (member) => member.wire_value,
    );
    metadata[definition.name] = {
      kind: definition.kind,
      module: definition.module,
    };
  }
  return `/**
 * Generated from every \`pg_enum!\` and \`wire_enum!\` declaration in Rust.
 * Run \`pnpm generate:enum-catalog\`; do not edit this file by hand.
 */

export const ENUM_CATALOG = ${JSON.stringify(catalog, null, 2)} as const;

export const ENUM_METADATA = ${JSON.stringify(metadata, null, 2)} as const;

export type EnumName = keyof typeof ENUM_CATALOG;
export type EnumValue<Name extends EnumName> =
  (typeof ENUM_CATALOG)[Name][number];
export type EnumWireValue = EnumValue<EnumName>;
export type EnumMemberKey = {
  [Name in EnumName]: \`${memberKeyTemplate}\`;
}[EnumName];
`;
}

try {
  execFileSync(
    'cargo',
    [
      'run',
      '-q',
      '-p',
      'quant-pivot-xtask',
      '--',
      'enum-catalog-schema',
      '--output',
      generatedSchemaPath,
    ],
    { cwd: repositoryRoot, stdio: 'inherit' },
  );
  const schema = JSON.parse(await readFile(generatedSchemaPath, 'utf8'));
  assertSchema(schema);
  await mkdir(dirname(generatedOutputPath), { recursive: true });
  await writeFile(generatedOutputPath, renderCatalog(schema), 'utf8');
  execFileSync('pnpm', ['exec', 'oxfmt', generatedOutputPath], {
    cwd: uiRoot,
    stdio: 'inherit',
  });

  if (checkOnly) {
    const [expectedSchema, actualSchema, expectedTypes, actualTypes] =
      await Promise.all([
        readFile(schemaPath, 'utf8'),
        readFile(generatedSchemaPath, 'utf8'),
        readFile(outputPath, 'utf8'),
        readFile(generatedOutputPath, 'utf8'),
      ]);
    const staleArtifacts = [];
    if (expectedSchema !== actualSchema) staleArtifacts.push(schemaPath);
    if (expectedTypes !== actualTypes) staleArtifacts.push(outputPath);
    if (staleArtifacts.length > 0) {
      throw new Error(
        `Enum catalog artifacts are stale: ${staleArtifacts.join(', ')}. Run pnpm generate:enum-catalog.`,
      );
    }
    console.log('Rust enum catalog and generated TypeScript are in sync');
  } else {
    console.log(`generated ${outputPath}`);
  }
} finally {
  if (temporaryRoot) await rm(temporaryRoot, { force: true, recursive: true });
}
